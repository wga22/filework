CREATE SCHEMA IF NOT EXISTS tesla;

CREATE TABLE IF NOT EXISTS tesla.users (
    row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name TEXT NOT NULL,
    handle TEXT NOT NULL,
    last_seen TIMESTAMPTZ
);

ALTER TABLE tesla.users
DROP CONSTRAINT IF EXISTS users_user_id_handle_key;

DROP INDEX IF EXISTS tesla.users_user_id_handle_key;

ALTER TABLE tesla.users
DROP COLUMN IF EXISTS user_id;

CREATE UNIQUE INDEX IF NOT EXISTS users_user_name_handle_key
ON tesla.users (user_name, handle);

CREATE TABLE IF NOT EXISTS tesla.sessions (
    row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_row_id BIGINT NOT NULL REFERENCES tesla.users(row_id),
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ,
    duration_mins NUMERIC(12, 2) NOT NULL DEFAULT 0
);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'tesla'
          AND table_name = 'sessions'
          AND column_name = 'user_id'
    ) AND NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'tesla'
          AND table_name = 'sessions'
          AND column_name = 'user_row_id'
    ) THEN
        ALTER TABLE tesla.sessions RENAME COLUMN user_id TO user_row_id;
    END IF;
END;
$$;

CREATE UNIQUE INDEX IF NOT EXISTS sessions_one_open_per_user
ON tesla.sessions (user_row_id)
WHERE end_time IS NULL;